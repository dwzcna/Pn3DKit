using Pn3DKit.Models;
using Pn3DKit.Utils;

namespace Pn3DKit.Tests;

/// <summary>直接覆盖 SDK 适配所调用的元数据分类，不用预先放行的权限事实替代分类过程。</summary>
public sealed class PnPropertyMetadataTests
{
    /// <summary>普通字段不读取描述信息、不查询无关获取状态、不调用 Tag 格式流程。</summary>
    [Theory]
    [InlineData("Comment")]
    [InlineData("Description")]
    [InlineData("CustomText")]
    public void PlainTextDoesNotDependOnPresentationAcquisitionStatusOrTagFormat(string property)
    {
        var result = PnPropertyMetadataPolicy.Evaluate(new(property),
            ["DisplayName", "UIOrder", "Category", "Description", "CustomDisplayMetadata"],
            _ => throw new InvalidOperationException("描述数据不应被读取"), () => false,
            () => throw new InvalidOperationException("非获取属性不应查询状态"),
            () => throw new InvalidOperationException("无关位号格式读取失败"));
        Assert.True(result.Allowed, result.Reason);
    }

    /// <summary>空 Comment 与非空 Comment 使用相同字段权限，空值不导致无法输入。</summary>
    [Theory]
    [InlineData("")]
    [InlineData("原备注")]
    public void CommentPermissionDoesNotDependOnExistingValue(string value)
    {
        var spec = new PnPropertySpec(Guid.NewGuid(), 1, "Comment");
        var permission = Evaluate(new("Comment"));
        var result = PnPropertyPolicy.Merge([spec], [new("PnId:Valve", "阀门",
            [new(spec, FastPropertyValue.Value(value), permission)])]);
        Assert.True(result.Cells[0].Permission.Allowed);
        Assert.Equal(value, result.Cells[0].Value.Raw);
    }

    private static PnEditPermission Evaluate(PnColumnMetadata column, IReadOnlyDictionary<string, string?>? rules = null) =>
        PnPropertyMetadataPolicy.Evaluate(column, rules?.Keys ?? [], name => rules![name], () => false,
            () => throw new InvalidOperationException("非获取属性"), () => PnEditPermission.Writable);

    /// <summary>明确约束继续阻止写入，不因为描述元数据被忽略而放宽系统字段。</summary>
    [Theory]
    [InlineData("readonly")]
    [InlineData("system")]
    [InlineData("autogenerated")]
    [InlineData("counter")]
    [InlineData("expression")]
    [InlineData("extension")]
    [InlineData("unique")]
    [InlineData("unsupported")]
    public void RealSdkRestrictionsRemainReadOnly(string kind)
    {
        var metadata = new PnColumnMetadata("Comment");
        metadata = kind switch
        {
            "readonly" => metadata with { ReadOnly = true },
            "system" => metadata with { System = true },
            "autogenerated" => metadata with { Autogenerated = true },
            "counter" => metadata with { Counter = true },
            "expression" => metadata with { Expression = true },
            "extension" => metadata with { Extension = true },
            "unique" => metadata with { Unique = true },
            _ => metadata with { SupportedType = false }
        };
        Assert.False(Evaluate(metadata).Allowed);
    }

    /// <summary>已确认约束的布尔扩展值参与判断，空描述值不覆盖 SDK 标志。</summary>
    [Theory]
    [InlineData("ReadOnly", "true", false)]
    [InlineData("IsReadOnly", "1", false)]
    [InlineData("ReadOnly", "false", true)]
    [InlineData("IsReadOnly", "0", true)]
    [InlineData("ReadOnly", "", true)]
    [InlineData("ReadOnly", null, true)]
    [InlineData("IsSystem", "true", false)]
    [InlineData("Autogenerated", "true", false)]
    [InlineData("IsCounter", "1", false)]
    [InlineData("Expression", "OtherProperty + 1", false)]
    [InlineData("IsExpression", "false", true)]
    public void KnownColumnConstraintsAreClassified(string key, string? value, bool allowed)
    {
        var result = Evaluate(new("Comment"), new Dictionary<string, string?> { [key] = value });
        Assert.Equal(allowed, result.Allowed);
    }

    /// <summary>SDK 已标记只读时，扩展属性 false 不能解除只读。</summary>
    [Fact]
    public void ExplicitFalseDoesNotOverrideSdkReadOnlyFlag() =>
        Assert.False(Evaluate(new("Comment", ReadOnly: true), new Dictionary<string, string?> { ["ReadOnly"] = "false" }).Allowed);

    /// <summary>无法解析的必要约束保守只读并显示原始信息。</summary>
    [Fact]
    public void UnknownConstraintValueIsReadOnlyWithReason()
    {
        var result = Evaluate(new("Comment"), new Dictionary<string, string?> { ["ReadOnly"] = "custom-rule" });
        Assert.False(result.Allowed); Assert.Contains("ReadOnly=custom-rule", result.Reason);
    }

    /// <summary>必要 SDK 元数据读取失败必须保留错误码，不变成普通空值。</summary>
    [Fact]
    public void RequiredMetadataFailurePreservesSdkDetails()
    {
        var result = PnPropertyMetadataPolicy.Evaluate(new("Comment"), ["ReadOnly"],
            _ => throw new InvalidOperationException("InvalidInput"), () => false, () => null,
            () => PnEditPermission.Writable, ex => "SDK ErrorStatus=" + ex.Message);
        Assert.False(result.Allowed); Assert.Contains("SDK ErrorStatus=InvalidInput", result.Reason);
    }

    /// <summary>真实获取规则保持只读，不执行 Tag 流程或改变获取模式。</summary>
    [Theory]
    [InlineData("Acquired")]
    [InlineData(null)]
    public void AcquisitionDefinitionRemainsReadOnly(string? status)
    {
        int reads = 0;
        var result = PnPropertyMetadataPolicy.Evaluate(new("Size"), [], _ => null, () => true,
            () => { reads++; return status; }, () => throw new InvalidOperationException("不应读取 Tag"));
        Assert.False(result.Allowed); Assert.Equal(1, reads); Assert.Contains("获取属性", result.Reason);
    }

    /// <summary>无法读取获取定义时不放行。</summary>
    [Fact]
    public void AcquisitionRuleFailureIsNotTreatedAsWritable()
    {
        var result = PnPropertyMetadataPolicy.Evaluate(new("Comment"), [], _ => null,
            () => throw new InvalidOperationException("获取定义不可用"), () => null, () => PnEditPermission.Writable);
        Assert.False(result.Allowed); Assert.Contains("获取定义不可用", result.Reason);
    }

    /// <summary>只有 Tag 才依赖登记和格式校验，SDK 唯一列标志不绕开 Tag 专用规则。</summary>
    [Fact]
    public void TagStillRequiresDedicatedValidation()
    {
        int calls = 0;
        var result = PnPropertyMetadataPolicy.Evaluate(new("Tag", Unique: true), [], _ => null,
            () => false, () => null, () => { calls++; return PnEditPermission.ReadOnly("位号注册表不可用"); });
        Assert.False(result.Allowed); Assert.Equal(1, calls); Assert.Contains("注册表", result.Reason);
    }

    /// <summary>Tag 格式解析失败限制 Tag，不影响普通字段。</summary>
    [Fact]
    public void TagFormatFailureRemainsReadOnly()
    {
        var result = PnPropertyMetadataPolicy.Evaluate(new("Tag"), [], _ => null, () => false,
            () => null, () => throw new InvalidOperationException("位号格式解析失败"));
        Assert.False(result.Allowed); Assert.Contains("位号格式解析失败", result.Reason);
    }

    /// <summary>面板焦点不等于 CAD 命令；实际批次或命令始终阻止新读写。</summary>
    [Theory]
    [InlineData(false, false, false, true, false)]
    [InlineData(false, false, true, true, false)]
    [InlineData(false, false, true, false, false)]
    [InlineData(false, false, false, false, true)]
    [InlineData(true, false, true, true, true)]
    [InlineData(false, true, true, true, true)]
    [InlineData(false, true, false, true, true)]
    public void BusyStateDistinguishesInputFocusFromCommands(bool batch, bool command, bool quiescent, bool focus, bool busy) =>
        Assert.Equal(busy, PnPropertyPolicy.IsBusy(batch, command, quiescent, focus));
}
