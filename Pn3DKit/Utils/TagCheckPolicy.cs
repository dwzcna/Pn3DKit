using System.Text;
using System.Text.RegularExpressions;
using Pn3DKit.Models;

namespace Pn3DKit.Utils;

/// <summary>提供编号解析、位号比较及逐字段重建策略，不依赖 Autodesk。</summary>
public static class TagCheckPolicy
{
    /// <summary>Tag 为空时仅对 Piping 回退 LineNumberTag，读取错误交由调用方报告。</summary>
    public static string ReadExistingTag(string projectPart, Func<string, string> read)
    {
        string tag = read("Tag");
        return projectPart == "Piping" && string.IsNullOrWhiteSpace(tag) ? read("LineNumberTag") : tag;
    }
    /// <summary>解析单独的 *、0 或以逗号分隔的正整数和正向范围；编号从一开始。</summary>
    /// <param name="input">用户输入；空白等价于未选择。</param>
    /// <param name="count">当前可选类别数。</param>
    /// <returns>升序且去重的类别编号；输入无效时抛出带原因的异常。</returns>
    public static int[] ParseClasses(string? input, int count)
    {
        if (count < 0) throw new ArgumentOutOfRangeException(nameof(count));
        string text = input?.Trim() ?? "";
        if (text.Length == 0 || text == "0") return [];
        if (text == "*") return Enumerable.Range(1, count).ToArray();
        var selected = new SortedSet<int>();
        foreach (string raw in text.Split(','))
        {
            string item = raw.Trim();
            if (!Regex.IsMatch(item, @"^[0-9]+(?:\s*-\s*[0-9]+)?$"))
                throw new ArgumentException("包含非法字符或空编号，请输入如 1,3,5-7，或单独的 *。");
            string[] ends = item.Split('-');
            if (!int.TryParse(ends[0].Trim(), out int first)
                || !int.TryParse(ends[^1].Trim(), out int last))
                throw new ArgumentException("类别编号过大。");
            if (first > last) throw new ArgumentException("不允许反向区间：" + item);
            if (first < 1 || last > count)
                throw new ArgumentException($"类别编号须在 1 到 {count} 之间；0 只能单独输入。");
            for (int number = first; ; number++)
            {
                selected.Add(number);
                if (number == last) break;
            }
        }
        return selected.ToArray();
    }

    /// <summary>非自动编号字段按已读取属性格式化；N／NN／NNN 使用 SDK 数字格式化，其余保留片段求值。</summary>
    /// <param name="property">完整属性路径，用于失败诊断。</param>
    /// <param name="raw">已读取且未格式化的属性值，不以 Tag 中的旧片段代替。</param>
    /// <param name="formatCharacters">SDK 拆分的格式字符，精确识别 N、NN、NNN。</param>
    /// <param name="formatNumerals">SDK FormatNumerals 回调；由适配层补充原始错误状态。</param>
    /// <param name="evaluate">非数字格式的原片段求值回调，不用于数字字段。</param>
    /// <returns>已格式化字段；数字非空却返回空值时抛出带完整上下文的异常，取消继续传播。</returns>
    public static string FormatProperty(string property, string raw, string? formatCharacters,
        Func<string, string, string?> formatNumerals, Func<string?> evaluate)
    {
        if (formatCharacters is not ("N" or "NN" or "NNN"))
            return evaluate() ?? throw new InvalidOperationException("SDK 未返回字段值。");
        try
        {
            string? expected = formatNumerals(formatCharacters, raw);
            if (expected == null || (raw.Length != 0 && expected.Length == 0))
                throw new InvalidOperationException("SDK FormatNumerals 返回空结果，未提供 ErrorStatus。");
            return expected;
        }
        catch (OperationCanceledException) { throw; }
        catch (Exception ex)
        {
            throw new InvalidOperationException(
                $"字段格式化失败：属性 {property}，原值「{raw}」，格式 {formatCharacters}；{ex.Message}", ex);
        }
    }

    /// <summary>在保留原格式字面量的前提下替换字段；先验证旧值能逐字符回拼为现有 Tag。</summary>
    /// <remarks>无法对应字段或字段边界不可靠时抛出异常，不推测自动编号。</remarks>
    public static string Reconstruct(string format, string existingTag, IReadOnlyList<TagCheckField> fields)
    {
        var matches = Regex.Matches(format, @"#\([^()]*\)");
        if (matches.Count != fields.Count)
            throw new InvalidOperationException("SDK 拆分字段数与格式片段数不符，无法可靠重建。");
        string Render(bool current)
        {
            var value = new StringBuilder();
            int offset = 0;
            for (int i = 0; i < matches.Count; i++)
            {
                var token = matches[i];
                var field = fields[i];
                if (!token.Value.Equals(field.Token, StringComparison.Ordinal))
                    throw new InvalidOperationException("SDK 拆分字段与格式顺序不符，无法可靠重建。");
                value.Append(format, offset, token.Index - offset);
                value.Append(current && !field.AutoGenerated ? field.ExpectedValue : field.ExistingValue);
                offset = token.Index + token.Length;
            }
            return value.Append(format, offset, format.Length - offset).ToString();
        }
        if (!Render(false).Equals(existingTag, StringComparison.Ordinal))
            throw new InvalidOperationException("现有 Tag 无法按格式可靠拆分并回拼；可能存在变化后的相邻字段或分隔符冲突。");
        return Render(true);
    }

    /// <summary>统一处理早退状态、SDK 重建、保留编号的兜底和 Ordinal 比较。</summary>
    /// <param name="subject">已定位对象的只读数据。</param>
    /// <param name="rebuild">仅返回重建字符串的 SDK 回调。</param>
    /// <param name="readFields">拆出旧字段并读取当前属性；不得生成编号或写回。</param>
    /// <returns>六种状态之一；重建失败保留原因，不向宿主传播普通异常。</returns>
    public static TagCheckResult Check(TagCheckSubject subject, Func<string> rebuild,
        Func<IReadOnlyList<TagCheckField>> readFields)
    {
        if (string.IsNullOrWhiteSpace(subject.Format))
            return new(subject, "", TagCheckStatus.NoFormat, []);
        if (string.IsNullOrWhiteSpace(subject.ExistingTag))
            return new(subject, "", TagCheckStatus.NoTag, []);
        if (subject.ExistingTag.StartsWith("?", StringComparison.Ordinal))
            return new(subject, "", TagCheckStatus.TemporaryTag, []);

        string? sdkExpected = null, sdkFailure = null;
        try { sdkExpected = rebuild(); }
        catch (OperationCanceledException) { throw; }
        catch (Exception ex) { sdkFailure = ex.Message; }
        try
        {
            var fields = readFields();
            string reconstructed = Reconstruct(subject.Format, subject.ExistingTag, fields);
            // 回拼验证同时保护自动编号；SDK 被禁用或返回不同结果时采用已验证的字段重建。
            string expected = string.Equals(sdkExpected, reconstructed, StringComparison.Ordinal)
                ? sdkExpected! : reconstructed;
            string? note = sdkFailure == null
                ? (sdkExpected == expected ? null : "SDK 重建未返回相同结果，已采用保留现有编号的逐字段重建。")
                : "SDK 重建失败，已采用逐字段重建：" + sdkFailure;
            var differences = fields.Where(f => !f.AutoGenerated && f.Property.Length != 0
                    && !f.ExistingValue.Equals(f.ExpectedValue, StringComparison.Ordinal))
                .Select(f => new TagFieldDifference(f.Property, f.ExistingValue, f.CurrentValue)).ToArray();
            return new(subject, expected,
                subject.ExistingTag.Equals(expected, StringComparison.Ordinal)
                    ? TagCheckStatus.Consistent : TagCheckStatus.Mismatch, differences, Note: note);
        }
        catch (OperationCanceledException) { throw; }
        catch (Exception ex)
        {
            return new(subject, "", TagCheckStatus.Error, [],
                ex.Message + (sdkFailure == null ? "" : "；SDK 重建：" + sdkFailure));
        }
    }

    /// <summary>用扫描时的类别补全失效对象的错误身份，类别变化时要求重新扫描。</summary>
    public static TagCheckResult BindToScannedClass(TagCheckResult item, string partName, string className)
    {
        var cached = item.Subject with { ProjectPart = partName, ClassName = className };
        if (item.Subject.ClassName.Length != 0 && (item.Subject.ClassName != className
            || item.Subject.ProjectPart != partName))
            return new(cached, "", TagCheckStatus.Error, [],
                $"对象所属类别已变化：原 {partName}/{className}，现 {item.Subject.ProjectPart}/{item.Subject.ClassName}；请重新扫描。");
        return item with { Subject = cached };
    }

    /// <summary>按统一顺序列出六种状态数量；空记录同样返回全部零值。</summary>
    public static string Summary(IEnumerable<TagCheckResult> items)
    {
        var counts = items.GroupBy(x => x.Status).ToDictionary(g => g.Key, g => g.Count());
        return string.Join("／", Enum.GetValues<TagCheckStatus>().Select(status =>
            new TagCheckResult(new("", "", "", "", ""), "", status, []).StatusText
            + " " + counts.GetValueOrDefault(status)));
    }
}
