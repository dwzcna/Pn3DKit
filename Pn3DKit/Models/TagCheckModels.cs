namespace Pn3DKit.Models;

/// <summary>位号检查的六种逐对象状态；取消属于批次状态。</summary>
public enum TagCheckStatus { Consistent, Mismatch, NoFormat, NoTag, TemporaryTag, Error }

/// <summary>区分普通元件、SLINE 和无独立图形的管线组。</summary>
public enum TagTargetKind { Component, LineSegment, LineGroup }

/// <summary>保存不依赖 CAD 的检查输入及真实项目数据身份。</summary>
public sealed record TagCheckSubject(string ProjectPart, string ClassName, string Handle,
    string Format, string ExistingTag)
{
    /// <summary>真实项目行 ID；旧的离线输入可保持为空。</summary>
    public string RowId { get; init; } = "";
    /// <summary>真实类别继承确定的目标种类。</summary>
    public TagTargetKind Kind { get; init; }
    /// <summary>关联图纸的完整路径，不使用路径充当数据库身份。</summary>
    public IReadOnlyList<string> Drawings { get; init; } = [];
    /// <summary>组目标的关联成员句柄说明，不伪造组自身句柄。</summary>
    public string RelatedHandles { get; init; } = "";
    /// <summary>日志中可辨认的行、图形及共享范围。</summary>
    public string Identity => $"数据行 {RowId}；句柄 {Handle}"
        + (RelatedHandles.Length == 0 ? "" : "；成员 " + RelatedHandles)
        + (Drawings.Count == 0 ? "" : "；图纸 " + string.Join("、", Drawings));
}

/// <summary>保存一个格式字段的现有片段、当前原始属性和格式化后的期望片段。</summary>
/// <param name="Token">包含 #() 的完整格式片段。</param>
/// <param name="Property">用于诊断的完整类别／属性名称；纯输入段为空。</param>
/// <param name="ExistingValue">从现有 Tag 拆出的字符串，不含外部字面量。</param>
/// <param name="CurrentValue">当前属性的原始值，用于差异说明。</param>
/// <param name="ExpectedValue">按字段规则格式化后的当前值。</param>
/// <param name="AutoGenerated">是否必须保留现有值的自动编号段。</param>
public sealed record TagCheckField(string Token, string Property, string ExistingValue,
    string CurrentValue, string ExpectedValue, bool AutoGenerated);

/// <summary>保存一个发生变化的属性及其在现有 Tag 中的片段。</summary>
public sealed record TagFieldDifference(string Property, string TagValue, string CurrentValue)
{
    /// <summary>返回命令行与日志共用的差异说明。</summary>
    public override string ToString() => $"{Property}：Tag 中为 {TagValue}，当前属性为 {CurrentValue}";
}

/// <summary>保存单对象检查结果，不持有 Autodesk 对象或数据库事务。</summary>
public sealed record TagCheckResult(TagCheckSubject Subject, string ExpectedTag, TagCheckStatus Status,
    IReadOnlyList<TagFieldDifference> Differences, string? Error = null, string? Note = null)
{
    /// <summary>返回稳定的中文结果名称，CSV 使用同一口径。</summary>
    public string StatusText => Status switch
    {
        TagCheckStatus.Consistent => "一致",
        TagCheckStatus.Mismatch => "不符",
        TagCheckStatus.NoFormat => "无格式",
        TagCheckStatus.NoTag => "无 Tag",
        TagCheckStatus.TemporaryTag => "临时 Tag",
        _ => "错误"
    };

    /// <summary>合并差异及诊断，CSV 会将换行作为字段内容转义。</summary>
    public string Details => string.Join("\n", Differences.Select(x => x.ToString())
        .Concat(new[] { Error, Note }.Where(x => !string.IsNullOrEmpty(x))!));

    /// <summary>生成用户可直接阅读的单对象检查结论。</summary>
    public string Message => Status switch
    {
        TagCheckStatus.Consistent => "位号一致：" + Subject.ExistingTag,
        TagCheckStatus.Mismatch => $"位号不符：现有 {Subject.ExistingTag}；按格式应为 {ExpectedTag}",
        TagCheckStatus.NoFormat => "所选 Plant 部件未配置位号格式。",
        TagCheckStatus.NoTag => "所选 Plant 部件没有 Tag。",
        TagCheckStatus.TemporaryTag => "临时 Tag：" + Subject.ExistingTag,
        _ => "位号检查错误：" + Error
    };
}

/// <summary>保存已完成记录及批次停止原因；未处理项不伪造对象状态。</summary>
public sealed record TagCheckBatchResult(int Total, IReadOnlyList<TagCheckResult> Items,
    bool Interrupted, string? StopReason)
{
    /// <summary>返回未完成的对象数量。</summary>
    public int Remaining => Total - Items.Count;
}
